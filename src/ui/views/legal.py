def render_privacy() -> None:
    """Render the Privacy Policy page."""
    st.title("Privacy Policy")
    st.caption(UPDATED)
    st.markdown(
        """
#### What this dashboard collects
Vayu has no accounts, sign-up forms or analytics code. It does not store information about visitors.
Filters you choose, such as station or date window, live in your browser session while the page is open.

#### Server logs
Whoever hosts the dashboard may keep standard web server logs, such as IP address and request time.
Those logs are controlled by the host, not by this application.

#### Data the pipeline processes
The pipeline works on environmental data only: air quality, weather and station readings for seven
fixed monitoring locations in Delhi NCR. It does not process personal data.

#### Third-party services
The pipeline server (not your browser) sends requests to these services:
- OpenWeatherMap, OpenAQ and Open-Meteo, with the coordinates of the seven monitoring locations.
- OpenAI, with a summary of current air quality, weather, anomalies and forecasts, to write the advisory.

None of these requests include information about dashboard visitors.

#### Cookies and browser storage
The dashboard sets no cookies of its own. The Streamlit framework may use browser storage to keep your
session working.

#### Your choices
Because the dashboard holds no personal information about you, there is nothing to access or delete.
If the host's logs concern you, contact the host.
"""
    )
